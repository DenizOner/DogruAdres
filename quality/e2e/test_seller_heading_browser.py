"""Chrome verification of actual SellerHeading.tsx with isolated child widgets.

This runs the PR source and locked sanitizer in a real browser. The Seller API,
Next.js page, login, server data, HTTP and hydration are NOT exercised.
"""
import os
import unittest
from pathlib import Path

from playwright.sync_api import sync_playwright


class SellerHeadingChromiumTest(unittest.TestCase):
    def setUp(self):
        bundle = Path(os.environ["BROWSER_TEST_BUNDLE"])
        if not bundle.is_file():
            self.fail("Expected real SellerHeading browser bundle in runner temp")
        self.playwright = sync_playwright().start()
        self.browser = self.playwright.chromium.launch(headless=True)
        self.page = self.browser.new_page(locale="tr-TR")
        self.errors = []
        self.page.on("pageerror", lambda error: self.errors.append(str(error)))
        # No request generated by a synthetic description may reach the network.
        self.page.route("**/*", lambda route: route.abort())
        self.page.set_content('<html lang="tr"><body><div id="app"></div></body></html>')
        self.page.evaluate("window.__daXssTriggered = 0")
        self.page.add_script_tag(path=str(bundle))
        self.page.wait_for_function("typeof window.__daRenderSeller === 'function'")

    def tearDown(self):
        try:
            self.assertEqual(self.errors, [], "Browser runtime errors")
        finally:
            self.browser.close()
            self.playwright.stop()

    def render(self, html, expected_text):
        self.page.evaluate("(description) => window.__daRenderSeller(description)", html)
        self.page.wait_for_function(
            "(expected) => document.querySelector('div.label-md')?.textContent === expected",
            arg=expected_text,
        )
        return self.page.locator("div.label-md")

    def test_safe_html_and_link_attributes(self):
        body = self.render(
            '<p><strong>Başlık</strong><br>Satır</p><a href="https://example.invalid/about">Bilgi</a>',
            "BaşlıkSatırBilgi",
        )
        self.assertEqual(body.locator("strong").count(), 1)
        self.assertEqual(body.locator("br").count(), 1)
        link = body.locator("a")
        self.assertEqual(link.get_attribute("href"), "https://example.invalid/about")
        self.assertEqual(link.get_attribute("rel"), "noopener noreferrer nofollow")
        self.assertEqual(link.get_attribute("target"), "_blank")

    def test_script_and_image_event_never_execute(self):
        body = self.render(
            '<p>Güvenli<script>window.__daXssTriggered=1</script><strong>metin</strong></p>'
            '<img src="https://synthetic.invalid/bad.png" onerror="window.__daXssTriggered=2">',
            "Güvenlimetin",
        )
        self.assertEqual(body.locator("script").count(), 0)
        self.assertEqual(body.locator("[onerror]").count(), 0)
        self.page.wait_for_timeout(150)
        self.assertEqual(self.page.evaluate("window.__daXssTriggered"), 0)

    def test_javascript_link_click_and_re_render(self):
        body = self.render(
            '<a href="javascript:window.__daXssTriggered=3">Tıkla</a>',
            "Tıkla",
        )
        link = body.locator("a")
        self.assertIsNone(link.get_attribute("href"))
        link.click()
        self.assertEqual(self.page.evaluate("window.__daXssTriggered"), 0)
        new_body = self.render("Yeni güvenli açıklama", "Yeni güvenli açıklama")
        self.assertEqual(new_body.locator("a").count(), 0)
        self.assertNotIn("javascript:", new_body.inner_html().lower())

    def test_nested_markup_and_blocked_elements(self):
        body = self.render(
            '<p>Ön<script>window.__daXssTriggered=4</script>'
            '<strong>son</strong><iframe src="https://synthetic.invalid/evil"></iframe>'
            '<style>body{display:none}</style></p>',
            "Önson",
        )
        self.assertEqual(body.locator("script,iframe,style").count(), 0)
        self.assertEqual(body.locator("strong").count(), 1)
        self.assertEqual(self.page.evaluate("window.__daXssTriggered"), 0)


if __name__ == "__main__":
    unittest.main()
